/**
 * Retrieves the photographic media record for a given question ID or asset key.
 * Robust lookup supports question ID, asset ID, or display key.
 */
export function getQuestionMedia(keyOrId: string): QuestionMediaRecord | null {
  if (!keyOrId) return null;
  if (QUESTION_MEDIA_REGISTRY[keyOrId]) {
    return QUESTION_MEDIA_REGISTRY[keyOrId];
  }
  const match = Object.values(QUESTION_MEDIA_REGISTRY).find(
    (m) => m.assetId === keyOrId || m.questionId === keyOrId
  );
  return match || null;
}
